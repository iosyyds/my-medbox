// 从识别文本中匹配药品
export function matchMedicineFromText(text) {
  if (!text) return null;
  const lowerText = text.toLowerCase().replace(/\s+/g, '');

  let bestMatch = null;
  let bestScore = 0;

  for (const med of medicineDatabase) {
    if (lowerText.includes(med.name.toLowerCase().replace(/\s+/g, ''))) {
      const score = med.name.length;
      if (score > bestScore) {
        bestScore = score;
        bestMatch = med;
      }
    }
    for (const alias of med.aliases) {
      const aliasLower = alias.toLowerCase().replace(/\s+/g, '');
      if (lowerText.includes(aliasLower) && aliasLower.length >= 2) {
        const score = alias.length;
        if (score > bestScore) {
          bestScore = score;
          bestMatch = med;
        }
      }
    }
  }

  return bestMatch;
}

// 搜索药品（用于搜索建议）
export function searchMedicine(query) {
  if (!query || query.trim().length < 1) return [];
  const q = query.toLowerCase().trim();
  const results = [];

  for (const med of medicineDatabase) {
    if (
      med.name.toLowerCase().includes(q) ||
      med.aliases.some((a) => a.toLowerCase().includes(q)) ||
      med.effect.toLowerCase().includes(q) ||
      med.tags.some((t) => t.toLowerCase().includes(q))
    ) {
      results.push(med);
    }
  }

  return results.slice(0, 10);
}
