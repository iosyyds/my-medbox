// AI关键词生成
export function generateKeywords(input) {
  if (!input) return [];
  let results = [];
  
  // 精确匹配药品
  for (const [med, kws] of Object.entries(medMap)) {
    if (input.includes(med) || med.includes(input)) {
      results = kws.map((k) => ({ main: k, sub: `与「${med}」相关` }));
      break;
    }
  }
  
  // 匹配症状
  if (results.length === 0) {
    for (const [sym, kws] of Object.entries(symptomMap)) {
      if (input.includes(sym) || sym.includes(input)) {
        results = kws.map((k) => ({ main: k, sub: `针对「${sym}」症状` }));
        break;
      }
    }
  }
  
  // 默认生成
  if (results.length === 0) {
    results = [
      { main: input, sub: '原始关键词' },
      { main: `${input} 功效`, sub: '查看功效说明' },
      { main: `${input} 用法`, sub: '查看用法用量' },
      { main: `${input} 副作用`, sub: '查看不良反应' },
      { main: `${input} 禁忌`, sub: '查看禁忌人群' },
      { main: `${input} 保质期`, sub: '查看有效期' },
    ];
  }
  
  return results.slice(0, 6);
}

export function getAllMedKeywords() {
  return Object.keys(medMap);
}

export function getAllSymptomKeywords() {
  return Object.keys(symptomMap);
}
